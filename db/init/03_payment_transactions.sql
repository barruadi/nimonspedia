-- Payment Transaction Status Enum
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'payment_status') THEN
        CREATE TYPE payment_status AS ENUM ('pending', 'success', 'failed', 'expired', 'cancelled');
    END IF;
END$$;

-- Payment Transaction Type Enum
DO $$
BEGIN
    IF NOT EXISTS (SELECT 1 FROM pg_type WHERE typname = 'payment_type') THEN
        CREATE TYPE payment_type AS ENUM ('topup', 'order');
    END IF;
END$$;

-- Payment Transactions Table
-- This table tracks all payment transactions for idempotency and audit purposes
CREATE TABLE IF NOT EXISTS payment_transactions (
    id                    INTEGER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,

    -- Midtrans transaction identifier (used for idempotency)
    transaction_id        TEXT NOT NULL UNIQUE,
    order_id              TEXT NOT NULL,

    -- User and order references
    user_id               INTEGER NOT NULL REFERENCES users(user_id) ON DELETE CASCADE,
    related_order_id      INTEGER REFERENCES orders(order_id) ON DELETE SET NULL,

    -- Transaction details
    type                  payment_type NOT NULL,
    gross_amount          INTEGER NOT NULL CHECK (gross_amount > 0),
    status                payment_status NOT NULL DEFAULT 'pending',

    -- Payment method info
    payment_type_midtrans TEXT,
    bank                  TEXT,
    va_number             TEXT,

    -- Midtrans response data (JSON for flexibility)
    midtrans_response     JSONB,

    -- Signature verification
    signature_key         TEXT,

    -- Idempotency tracking
    processed_at          TIMESTAMPTZ,
    retry_count           INTEGER NOT NULL DEFAULT 0,

    -- Timestamps
    created_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at            TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    -- Indexes for common queries
    CONSTRAINT unique_transaction_per_order UNIQUE(transaction_id, order_id)
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_payment_transactions_user_id ON payment_transactions(user_id);
CREATE INDEX IF NOT EXISTS idx_payment_transactions_order_id ON payment_transactions(related_order_id);
CREATE INDEX IF NOT EXISTS idx_payment_transactions_status ON payment_transactions(status);
CREATE INDEX IF NOT EXISTS idx_payment_transactions_created_at ON payment_transactions(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_payment_transactions_transaction_id ON payment_transactions(transaction_id);

-- Trigger to update updated_at timestamp
CREATE OR REPLACE FUNCTION update_payment_transactions_timestamp()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

CREATE TRIGGER trigger_update_payment_transactions_timestamp
    BEFORE UPDATE ON payment_transactions
    FOR EACH ROW
    EXECUTE FUNCTION update_payment_transactions_timestamp();

-- Comments for documentation
COMMENT ON TABLE payment_transactions IS 'Tracks all payment transactions for both top-up and order payments with idempotency support';
COMMENT ON COLUMN payment_transactions.transaction_id IS 'Midtrans transaction ID - used for idempotency checks';
COMMENT ON COLUMN payment_transactions.order_id IS 'Midtrans order ID generated by our system';
COMMENT ON COLUMN payment_transactions.related_order_id IS 'Reference to orders table for order payments, NULL for top-ups';
COMMENT ON COLUMN payment_transactions.type IS 'Type of payment: topup (balance top-up) or order (product purchase)';
COMMENT ON COLUMN payment_transactions.processed_at IS 'Timestamp when webhook was successfully processed';
COMMENT ON COLUMN payment_transactions.retry_count IS 'Number of times this transaction was processed (for monitoring duplicate webhooks)';
